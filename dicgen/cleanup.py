"""Output-directory preparation and cleanup.

Rules implemented here (see the task specification):

* if the output directory does not exist, it is created (parents included);
* if it exists, everything *this tool could have generated* is deleted before new
  files are written -- stale images from a longer previous run disappear;
* anything that is not recognisable as generated content ("foreign content") is
  left untouched and the run is refused with a clear message listing it, unless
  ``--overwrite`` was passed;
* the output directory itself is never deleted, and nothing outside it is ever
  touched (symbolic links are treated as foreign content and, with
  ``--overwrite``, are unlinked -- never followed).
"""

from __future__ import annotations

import os
import re
import shutil
from dataclasses import dataclass, field
from pathlib import Path
from typing import Iterable, List, Sequence

from .movie import MOVIE_FILENAME

__all__ = [
    "ForeignContentError",
    "CleanupPlan",
    "GENERATED_FILE_PATTERNS",
    "GENERATED_SUBDIRS",
    "scan_output_dir",
    "prepare_output_dir",
]

#: Regular expressions matching every file this tool writes (top level).
GENERATED_FILE_PATTERNS: Sequence[re.Pattern] = (
    re.compile(r"^image\d+\.png$"),
    re.compile(r"^ground_truth\.csv$"),
    re.compile(r"^ground_truth_grid\.csv$"),
    re.compile(r"^metadata\.json$"),
    re.compile(r"^displacement_field\.npy$"),
    re.compile(rf"^{re.escape(MOVIE_FILENAME)}$"),
)

#: Sub-directories owned by this tool, with the patterns allowed inside them.
GENERATED_SUBDIRS = {
    "masks": (re.compile(r"^mask\d+\.png$"),),
    "qa": (
        re.compile(r"^disp_\d+\.png$"),
        re.compile(r"^arrows_\d+\.png$"),
    ),
}


class ForeignContentError(RuntimeError):
    """The output directory holds content this tool did not generate."""


@dataclass
class CleanupPlan:
    """What :func:`prepare_output_dir` will do (or did) with the directory."""

    output_dir: Path
    existed: bool = False
    to_delete: List[Path] = field(default_factory=list)
    foreign: List[Path] = field(default_factory=list)
    deleted: List[Path] = field(default_factory=list)
    refused: bool = False
    overwrite: bool = False

    @property
    def relative_deletions(self) -> List[str]:
        return [str(p.relative_to(self.output_dir)) for p in self.to_delete]

    @property
    def relative_foreign(self) -> List[str]:
        return [str(p.relative_to(self.output_dir)) for p in self.foreign]


def _matches(name: str, patterns: Iterable[re.Pattern]) -> bool:
    return any(pattern.match(name) for pattern in patterns)


def _is_generated_dir(directory: Path) -> bool:
    """True if ``directory`` has a known name and contains only known files."""
    patterns = GENERATED_SUBDIRS.get(directory.name)
    if patterns is None:
        return False
    for entry in directory.iterdir():
        if entry.is_symlink() or not entry.is_file():
            return False
        if not _matches(entry.name, patterns):
            return False
    return True


def scan_output_dir(output_dir: Path, *, overwrite: bool = False) -> CleanupPlan:
    """Inspect ``output_dir`` and decide what may be deleted.

    Raises :class:`ForeignContentError` if unrecognised content is found and
    ``overwrite`` is false.
    """
    output_dir = Path(output_dir)
    plan = CleanupPlan(output_dir=output_dir, overwrite=overwrite)
    if not output_dir.exists():
        return plan
    if not output_dir.is_dir():
        raise ForeignContentError(
            f"{output_dir} exists but is not a directory; refusing to touch it"
        )
    plan.existed = True

    entries = sorted(output_dir.iterdir(), key=lambda p: p.name)
    for entry in entries:
        if entry.is_symlink():
            plan.foreign.append(entry)
        elif entry.is_file():
            if _matches(entry.name, GENERATED_FILE_PATTERNS):
                plan.to_delete.append(entry)
            else:
                plan.foreign.append(entry)
        elif entry.is_dir():
            if _is_generated_dir(entry):
                plan.to_delete.append(entry)
            else:
                plan.foreign.append(entry)
        else:  # sockets, fifos, devices -- never touch them
            plan.foreign.append(entry)

    if plan.foreign and not overwrite:
        plan.refused = True
        raise ForeignContentError(
            f"{output_dir} contains {len(plan.foreign)} item(s) that were not "
            "generated by this tool:\n  "
            + "\n  ".join(plan.relative_foreign)
            + "\nRefusing to delete them. Re-run with --overwrite to delete "
            "everything inside the directory, or choose a different "
            "--output-dir."
        )
    if plan.foreign and overwrite:
        # With --overwrite every entry of the directory is fair game.
        plan.to_delete = entries
    return plan


def _delete_entry(entry: Path) -> None:
    """Delete a file, symlink or directory *inside* the output directory."""
    if entry.is_symlink() or entry.is_file():
        os.unlink(entry)
    else:
        shutil.rmtree(entry)


def _guard_dangerous_path(output_dir: Path) -> None:
    """Refuse obviously dangerous output directories (safety net)."""
    resolved = Path(output_dir).resolve()
    if resolved == resolved.parent:
        raise ForeignContentError(
            f"refusing to use the filesystem root {resolved} as --output-dir"
        )
    home = Path.home().resolve()
    if resolved == home:
        raise ForeignContentError(
            f"refusing to use the home directory {resolved} as --output-dir; "
            "use a sub-directory instead"
        )
    if resolved == Path.cwd().resolve():
        raise ForeignContentError(
            f"refusing to use the current working directory {resolved} as "
            "--output-dir because existing content there would be deleted; "
            "use a sub-directory instead"
        )
    for parent in resolved.parents:
        if resolved == parent:  # pragma: no cover - covered by the root check
            raise ForeignContentError(f"refusing to use {resolved} as --output-dir")


def prepare_output_dir(
    output_dir: Path,
    *,
    overwrite: bool = False,
    dry_run: bool = False,
    announce=None,
) -> CleanupPlan:
    """Create/clean ``output_dir`` and return the :class:`CleanupPlan` that was executed.

    With ``dry_run`` the directory is inspected and the planned deletions are
    reported, but nothing is created or deleted.

    ``announce`` is a callable taking one message string; it defaults to
    ``print`` so that the list of deleted items is *always* visible to the user
    (independently of the logging verbosity), as required by the specification.
    Pass ``lambda message: None`` to silence it when using this function as a
    library.
    """
    output_dir = Path(output_dir)
    _guard_dangerous_path(output_dir)
    plan = scan_output_dir(output_dir, overwrite=overwrite)

    def emit(message: str) -> None:
        if announce is None:
            print(message)
        else:
            announce(message)

    if plan.to_delete:
        emit(
            f"Deleting {len(plan.to_delete)} previously generated item(s) in "
            f"{output_dir}:"
        )
        for item in plan.relative_deletions:
            emit(f"  - {item}")
    if dry_run:
        emit("--dry-run: nothing was created or deleted")
        return plan

    if not plan.existed:
        output_dir.mkdir(parents=True, exist_ok=True)
        emit(f"Created output directory {output_dir}")
    else:
        for entry in plan.to_delete:
            _delete_entry(entry)
            plan.deleted.append(entry)
        output_dir.mkdir(parents=True, exist_ok=True)
    return plan